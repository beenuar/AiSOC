"""Record real model replies to the real triage prompt, for replay in CI.

Fix pass item 3.5. See ``plans/aisoc_fix_pass_plan.plan.md``.

Why a recording exists at all
-----------------------------
``test_replay_runner.py`` has to prove two things about a replay run that pull
in opposite directions: the same history must produce the same decisions
twice, and the decisions must not all be the same decision. The second one is
what the deterministic tier cannot supply — it answers ``likely_benign`` at
0.10 for every alert, so a reproducibility assertion over it compares one
constant against itself and would pass over a runner that had stopped reading
its input.

A live model supplies the variety and destroys the reproducibility. A
recording supplies both: the replies are what a real model really said to the
real production prompt, and replaying them is byte-stable.

What is real here and what is not
---------------------------------
* The **replies** are real. They were generated by a local model answering the
  production triage prompt, over HTTP, through the gateway client the worker
  builds in ``app.llm.factory.make_chat_model``. Nothing was edited afterwards;
  a reply the parser rejects is recorded as it arrived.
* The **alerts** are synthetic. They are Splunk ES notable rows written for
  this fixture, not customer data, using RFC 5737 documentation addresses.

That distinction is the whole value of the file, so it is also written into
the fixture's ``provenance`` block where a reader of the data will see it.

Re-recording
------------
Any OpenAI-compatible endpoint serving a real model works. The recording
committed to the repository was produced with::

    ollama serve                       # in another terminal
    cd services/agents
    PYTHONPATH=. python tests/record_replay_triage.py \\
        --base-url http://127.0.0.1:11434/v1 --model llama3:8b

The script refuses to write a recording whose verdicts are all one class,
because such a recording would restore exactly the defect this item exists to
remove.
"""


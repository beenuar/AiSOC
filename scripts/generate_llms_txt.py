def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed files differ from what would be generated",
    )
    args = parser.parse_args(argv)

    try:
        outputs = build()
    except GenerationError as exc:
        print(f"LLMS-TXT GENERATION FAILED: {exc}", file=sys.stderr)
        return 1

    if args.check:
        drift = [path for path, content in outputs.items() if not path.is_file() or path.read_text(encoding="utf-8") != content]
        if drift:
            print("LLMS-TXT GATE FAILED:", file=sys.stderr)
            for path in drift:
                state = "missing" if not path.is_file() else "stale"
                print(f"  - {path.relative_to(REPO_ROOT)} is {state}.", file=sys.stderr)
            print(
                "    Run: python3 scripts/generate_llms_txt.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: llms.txt and llms-full.txt match their sources ({len(outputs)} files).")
        return 0

    STATIC_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

def connector_facts() -> tuple[int, dict[str, int]]:
    """Connector count and per-category breakdown, from the generated JSON."""
    if not CONNECTOR_COUNT_JSON.is_file():
        raise GenerationError(f"{CONNECTOR_COUNT_JSON.relative_to(REPO_ROOT)} is missing. Run scripts/generate_connector_count.py first.")
    data = json.loads(CONNECTOR_COUNT_JSON.read_text(encoding="utf-8"))
    count = data.get("count")
    categories = data.get("categories") or {}
    if not isinstance(count, int) or count <= 0:
        raise GenerationError(f"connector count is not a positive int: {count!r}")
    return count, {str(k): int(v) for k, v in categories.items()}


def detection_facts() -> tuple[int, int]:
    """(executable, on-disk) rule counts, parsed from the generated truth table.

    The distinction is the whole point and must survive into any summary: the
    YAML under `detections/` is a generated projection, and only the rules the
    engine actually loads can fire. Publishing the on-disk figure alone would
    overstate the corpus by roughly 8x.
    """
    if not TRUTH_TABLE.is_file():
        raise GenerationError(f"{TRUTH_TABLE.relative_to(REPO_ROOT)} is missing. Run scripts/detection_truth_table.py first.")
    text = TRUTH_TABLE.read_text(encoding="utf-8")

    executable = _parse_table_number(text, r"\*\*executable \(loaded by the engine\)\*\*\s*\|\s*\*\*(\d+)\*\*")
    on_disk = _parse_table_number(text, r"rules on disk \(total\)\s*\|\s*(\d+)")
    if executable > on_disk:
        raise GenerationError(f"executable ({executable}) exceeds on-disk ({on_disk}); truth table is inconsistent")
    return executable, on_disk


def _parse_table_number(text: str, pattern: str) -> int:
    match = re.search(pattern, text)
    if not match:
        raise GenerationError(
            f"could not find {pattern!r} in {TRUTH_TABLE.relative_to(REPO_ROOT)}. "
            "The truth table's format changed; update this parser rather than "
            "hard-coding the number."
        )
    return int(match.group(1))


def mcp_tool_names() -> list[str]:
    """Tool names the MCP server advertises, read from the tool definitions.

    Sorted for a stable artefact. The server's own advertised *order* is a
    deliberate discovery-before-deep-dive ordering that lives in
    `src/tools/index.ts`; this list is about membership, not order.
    """
    if not MCP_TOOLS_DIR.is_dir():
        raise GenerationError(f"{MCP_TOOLS_DIR.relative_to(REPO_ROOT)} is missing")
    names: set[str] = set()
    for path in sorted(MCP_TOOLS_DIR.glob("*.ts")):
        names.update(re.findall(r'name:\s*"(aisoc_[a-z_]+)"', path.read_text(encoding="utf-8")))
    if not names:
        raise GenerationError(f"no aisoc_* tool names found under {MCP_TOOLS_DIR.relative_to(REPO_ROOT)}")
    return sorted(names)


def windowed_rule_count() -> int:
    """Rules in the windowed engine's compiled ruleset, from the truth table.

    Published beside the executable figure rather than folded into it. A
    threshold over a sliding window and a single-event match are different
    kinds of claim, and a reader who adds them has one number describing two
    incomparable things.
    """
    if not TRUTH_TABLE.is_file():
        raise GenerationError(f"{TRUTH_TABLE.relative_to(REPO_ROOT)} is missing. Run scripts/detection_truth_table.py first.")
    return _parse_table_number(
        TRUTH_TABLE.read_text(encoding="utf-8"),
        r"windowed rules in `windowed_ruleset\.json`\s*\|\s*(\d+)",
    )


def profile_service_counts() -> tuple[int, int]:
    """(core, full) long-running service counts, from ``docker-compose.yml``.

    Imported from the gate that already owns this question rather than
    re-parsed here, because a second parser is a second answer. The gate's
    ``self_test_if_requested`` only fires for the process that was *launched*
    as that script, so importing it from here is safe — gates in this tree
    import one another on the same basis.
    """
    try:
        import check_profile_service_counts as profiles
    except ImportError as exc:  # pragma: no cover - the file is committed beside this one
        raise GenerationError(f"could not import check_profile_service_counts: {exc}") from exc
    counts, _members, _unregistered = profiles.scan()
    try:
        core, full = int(counts["core"]), int(counts["full"])
    except KeyError as exc:
        raise GenerationError(f"docker-compose.yml declares no {exc} profile; service counts are unavailable") from exc
    if core <= 0 or full < core:
        raise GenerationError(f"implausible service counts: core={core}, full={full}")
    return core, full


#: The two lines of ``.github/release-packages.yml`` this needs. Read line by
#: line rather than with PyYAML on purpose: the CI job that runs this gate
#: installs ruff and mypy and nothing else, so an ``import yaml`` here would
#: fail in CI while passing on every developer machine — the worst split there
#: is, because the failure appears only where nobody is watching it happen.
_PKG_NAME = re.compile(r"^\s*-\s+name:\s*['\"]?([^'\"\s]+)['\"]?\s*$")
_PKG_PUBLISHED = re.compile(r"^\s+published:\s*(true|false)\s*$")


def package_publication() -> tuple[list[str], list[str]]:
    """(published, unpublished) package names, from the release manifest.

    This file previously told machine readers that every AiSOC package was
    unpublished and that any install command "will fail today". Five of them
    had been resolving on PyPI for weeks. Reading the manifest means the
    sentence changes when the fact does.
    """
    if not RELEASE_PACKAGES.is_file():
        raise GenerationError(f"{RELEASE_PACKAGES.relative_to(REPO_ROOT)} is missing; publication status is unknowable")
    published: list[str] = []
    unpublished: list[str] = []
    current: str | None = None
    seen: set[str] = set()
    for line in RELEASE_PACKAGES.read_text(encoding="utf-8").splitlines():
        name_match = _PKG_NAME.match(line)
        if name_match:
            if current is not None and current not in seen:
                raise GenerationError(f"package {current!r} in {RELEASE_PACKAGES.name} declares no `published:` flag")
            current = name_match.group(1)
            continue
        flag = _PKG_PUBLISHED.match(line)
        if flag and current is not None:
            (published if flag.group(1) == "true" else unpublished).append(current)
            seen.add(current)
    if current is not None and current not in seen:
        raise GenerationError(f"package {current!r} in {RELEASE_PACKAGES.name} declares no `published:` flag")
    if not published and not unpublished:
        raise GenerationError(f"parsed no packages out of {RELEASE_PACKAGES.name}; refusing to publish an empty claim")
    return sorted(published), sorted(unpublished)


def version() -> str:
    if not VERSION_FILE.is_file():
        raise GenerationError("VERSION is missing")
    return VERSION_FILE.read_text(encoding="utf-8").strip()



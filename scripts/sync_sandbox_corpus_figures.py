#!/usr/bin/env python3
"""Keep the sandbox's ruleset figure derived from the tree, not retyped.

Why this exists
---------------
``packages/aisoc-sandbox`` printed ``{"rule_count": "800+"}`` inside a
simulated ``rules.match`` tool call. Two things were wrong with that and
only one of them is the number. The figure was hand-typed and had gone
stale by a factor of three while the engine grew past 2,500 executable
rules — but it also sat in the *arguments of a call that never happened*,
so a reader saw a rule count attached to a match the sandbox had not
performed. The call-shape question is fixed in the package; this script
fixes the staleness, the same way ``generate_connector_count.py`` and
``generate_corpus_stats.py`` already fix theirs: derive it, commit it,
gate it.

Why a committed constant rather than a read at runtime
------------------------------------------------------
``aisoc-sandbox`` is a zero-dependency wheel that a user installs from
PyPI with no checkout. It cannot read ``apps/web/src/data/corpus-stats.json``
at runtime because that file is not in the wheel, so the figure has to be
baked in at commit time and checked in CI — which is exactly the
sync-with-``--check`` shape ``sync_vendored_narrative.py`` uses for the
narrative module.

The source is ``corpus-stats.json`` rather than the ruleset artefacts
directly, deliberately: that file is itself generated by
``generate_corpus_stats.py``, which reconciles three independent counts
against each other and hard-errors on disagreement. Reading the
artefacts here would be a fourth counter that could drift from the other
three, which is the failure this repository keeps re-finding.

Usage
-----

    python3 scripts/sync_sandbox_corpus_figures.py            # write
    python3 scripts/sync_sandbox_corpus_figures.py --check    # fail on drift
    python3 scripts/sync_sandbox_corpus_figures.py --self-test
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# `scripts/` is on sys.path when this file is run as a program, but not when a
# test loads it by path with importlib. gate_toolkit sits beside it either way.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from gate_toolkit import repo_root, self_test_main

REPO_ROOT = repo_root()
SOURCE = REPO_ROOT / "apps" / "web" / "src" / "data" / "corpus-stats.json"
TARGET = REPO_ROOT / "packages" / "aisoc-sandbox" / "src" / "aisoc_sandbox" / "_corpus.py"

_TEMPLATE = '''"""Figures about the live stack, derived from the tree at commit time.

GENERATED FILE — do not edit by hand.

    Regenerate:  python3 scripts/sync_sandbox_corpus_figures.py
    Gate:        python3 scripts/sync_sandbox_corpus_figures.py --check

Source: ``{source}``, itself generated by ``scripts/generate_corpus_stats.py``
from the engine's own ruleset artefacts.

These describe the **full AiSOC stack**, not this package. The sandbox ships
no detection engine and evaluates none of these rules; the numbers exist so
the ledger can say what a real run would have had available without anyone
retyping a figure that then goes stale. The value is frozen at the version of
this wheel, which is why the rendered text says so.
"""

from __future__ import annotations

#: Rules the live fusion engine loads and can fire on a single event.
LIVE_ENGINE_EXECUTABLE_RULES = {executable}

#: Sliding-window rules the same worker loads; they need several events, so
#: they are published as their own figure rather than folded into the above.
LIVE_ENGINE_WINDOWED_RULES = {windowed}

#: Where the two numbers came from, so a reader can re-derive them.
LIVE_ENGINE_RULESET_SOURCE = "{source}"
'''


def _render_from(stats: object, source_label: str) -> str:
    """Validate a stats payload and render the module, or refuse.

    Separate from the file read so the self-test can drive the refusal
    paths with real inputs rather than re-asserting its own arithmetic.
    """

    if not isinstance(stats, dict):
        raise SystemExit(f"sync_sandbox_corpus_figures: {source_label} is not a JSON object")
    missing = [key for key in ("executable", "windowed") if not isinstance(stats.get(key), int) or isinstance(stats.get(key), bool)]
    if missing:
        raise SystemExit(
            f"sync_sandbox_corpus_figures: {source_label} has no integer {', '.join(missing)} — refusing to write a figure it did not read"
        )
    if stats["executable"] <= 0 or stats["windowed"] <= 0:
        raise SystemExit(
            f"sync_sandbox_corpus_figures: refusing a non-positive count ({stats['executable']}, {stats['windowed']});"
            " a read that found nothing must not become a published zero"
        )
    return _TEMPLATE.format(executable=stats["executable"], windowed=stats["windowed"], source=source_label)


def _render() -> str:
    if not SOURCE.exists():
        raise SystemExit(f"sync_sandbox_corpus_figures: source artefact is missing: {SOURCE}")
    try:
        stats = json.loads(SOURCE.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"sync_sandbox_corpus_figures: {SOURCE} is not valid JSON: {exc}") from exc
    return _render_from(stats, SOURCE.relative_to(REPO_ROOT).as_posix())


def _refuses(stats: object) -> bool:
    try:
        _render_from(stats, "<self-test>")
    except SystemExit:
        return True
    return False


def _self_test() -> int:
    """Prove the gate catches drift rather than only agreeing with the tree."""

    try:
        rendered = _render()
    except SystemExit as exc:
        print(f"  FAIL  renders from the committed artefact ({exc})")
        return 1

    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    drifted = rendered.replace("LIVE_ENGINE_EXECUTABLE_RULES = ", "LIVE_ENGINE_EXECUTABLE_RULES = 800  # ", 1)

    extra = [
        ("the committed module matches the artefact it is generated from", rendered == current),
        # The exact drift this gate exists for: the stale hand-typed 800+.
        # A gate that has only ever seen an in-sync tree has never been
        # shown to fail.
        ("the stale hand-typed figure would be detected as drift", drifted != current),
        ("a zero executable count is refused rather than published", _refuses({"executable": 0, "windowed": 76})),
        ("a missing key is refused rather than defaulted", _refuses({"windowed": 76})),
        ("a non-integer count is refused rather than coerced", _refuses({"executable": "2538", "windowed": 76})),
    ]
    return self_test_main("sync_sandbox_corpus_figures.py", ["--check"], extra=extra)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed module has drifted from the artefact")
    parser.add_argument("--self-test", action="store_true", help="prove the gate detects drift")
    args = parser.parse_args()

    if args.self_test:
        return _self_test()

    rendered = _render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            print(f"DRIFT: {TARGET.relative_to(REPO_ROOT)} is out of date.", file=sys.stderr)
            print("Regenerate with: python3 scripts/sync_sandbox_corpus_figures.py", file=sys.stderr)
            return 1
        print(f"OK: {TARGET.relative_to(REPO_ROOT)} matches {SOURCE.relative_to(REPO_ROOT)}")
        return 0

    TARGET.write_text(rendered, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
